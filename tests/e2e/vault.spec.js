import { expect, test } from '@playwright/test';

test('creates, locks, unlocks, changes its password, and restores an encrypted backup on another device', async ({ page, browser }) => {
  test.setTimeout(60000);
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.addInitScript(() => {
    const createObjectUrl = URL.createObjectURL.bind(URL);
    URL.createObjectURL = (value) => {
      if (value instanceof Blob) value.text().then((text) => { globalThis.__lastDownloadedText = text; });
      return createObjectUrl(value);
    };
  });
  await page.goto('/vault');
  await expect(page.getByRole('heading', { name: '创建密码本' })).toBeVisible();
  await page.getByLabel('创建保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByLabel('确认保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByText('我明白：必须把恢复密钥').click();
  await page.getByRole('button', { name: '创建并解锁' }).click();
  await expect(page.getByRole('heading', { name: '密码本', exact: true })).toBeVisible({ timeout: 15000 });
  const recoveryKey = await page.getByLabel('一次性显示的密码本恢复密钥').inputValue();
  expect(recoveryKey).toMatch(/^DVK1-/);
  await page.getByText('我已把恢复密钥保存在安全位置').click();
  await page.getByRole('button', { name: '我已安全保存' }).click();

  await page.getByRole('button', { name: '添加账号' }).click();
  await page.getByLabel('账号类型').selectOption('app');
  await page.getByLabel('应用或网站名称').fill('企业微信');
  await page.getByLabel('登录账号').fill('work-account@example.com');
  await page.getByRole('button', { name: '生成强密码' }).click();
  await expect(page.getByLabel('密码', { exact: true })).toHaveAttribute('type', 'text');
  const generatedPassword = await page.getByLabel('密码', { exact: true }).inputValue();
  expect(generatedPassword).toHaveLength(24);
  expect(generatedPassword).toMatch(/[a-z]/); expect(generatedPassword).toMatch(/[A-Z]/); expect(generatedPassword).toMatch(/[0-9]/);
  await page.getByLabel('密码', { exact: true }).fill('work-secret-password!');
  await page.getByLabel('App 标识（可选）').fill('com.tencent.wework');
  await page.getByLabel('备注（可选）').fill('工作账号');
  await page.getByLabel('标签（可选，用逗号分隔）').fill('工作，沟通');
  await page.getByText('动态验证码 TOTP（可选）').click();
  await page.getByLabel('动态验证码密钥（可选）').fill('JBSWY3DPEHPK3PXP');
  await page.getByLabel('动态验证码位数').selectOption('6');
  await page.getByLabel('动态验证码周期').selectOption('30');
  await page.getByText('收藏', { exact: true }).click();
  await page.getByRole('button', { name: '加密保存' }).click();
  await expect(page.getByRole('heading', { name: /企业微信/ })).toBeVisible({ timeout: 15000 });
  await expect(page.getByText('work-account@example.com')).toBeVisible();
  await page.getByRole('button', { name: '显示动态验证码' }).click();
  await expect(page.getByLabel('当前动态验证码')).toHaveText(/^\d{6} · \d{1,2} 秒内有效$/);
  await page.getByRole('button', { name: '显示动态验证码' }).click();
  await expect(page.getByLabel('当前动态验证码')).toBeHidden();
  await page.getByLabel('筛选账号记录').selectOption('website');
  await expect(page.getByText('work-account@example.com')).toHaveCount(0);
  await page.getByLabel('筛选账号记录').selectOption('favorite');
  await expect(page.getByText('work-account@example.com')).toBeVisible();
  await page.getByLabel('筛选账号记录').selectOption('tag:沟通');
  await expect(page.getByText('work-account@example.com')).toBeVisible();
  await page.getByLabel('搜索密码本').fill('工作');
  await expect(page.getByText('work-account@example.com')).toBeVisible();
  await page.getByLabel('搜索密码本').fill('');
  await page.getByLabel('筛选账号记录').selectOption('');
  await expect(page.getByText('work-secret-password!')).toHaveCount(0);
  await page.clock.install();
  await page.getByRole('button', { name: '查看密码' }).click();
  await expect(page.getByText('work-secret-password!')).toBeVisible();
  await page.clock.fastForward(30001); await page.clock.resume();
  await expect(page.getByText('work-secret-password!')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '查看密码' })).toBeVisible();

  const existingIds = await page.evaluate(() => new Promise((resolve, reject) => {
    const request = indexedDB.open('diary-v2:learning'); request.onerror = () => reject(request.error);
    request.onsuccess = () => { const read = request.result.transaction('vaultItems').objectStore('vaultItems').getAllKeys();
      read.onerror = () => reject(read.error); read.onsuccess = () => resolve(read.result); };
  }));
  await page.getByRole('button', { name: '添加账号' }).click();
  await page.getByLabel('应用或网站名称').fill('临时损坏测试');
  await page.getByLabel('登录账号').fill('damaged@example.com');
  await page.getByLabel('密码', { exact: true }).fill('temporary-damaged-password!');
  await page.getByRole('button', { name: '加密保存' }).click();
  await expect(page.getByRole('heading', { name: '临时损坏测试' })).toBeVisible();
  await page.evaluate((known) => new Promise((resolve, reject) => {
    const request = indexedDB.open('diary-v2:learning'); request.onerror = () => reject(request.error);
    request.onsuccess = () => {
      const db = request.result, transaction = db.transaction('vaultItems', 'readwrite'), table = transaction.objectStore('vaultItems'), read = table.getAll();
      read.onerror = () => reject(read.error); transaction.onerror = () => reject(transaction.error); transaction.oncomplete = () => resolve();
      read.onsuccess = () => { const record = read.result.find((candidate) => !known.includes(candidate.id));
        if (!record) { reject(new Error('new encrypted record not found')); return; }
        record.ciphertext = `${record.ciphertext.slice(0, -1)}${record.ciphertext.endsWith('A') ? 'B' : 'A'}`; table.put(record); };
    };
  }), existingIds);
  await page.reload();
  await page.getByLabel('保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByRole('button', { name: '解锁密码本' }).click();
  await expect(page.getByText('work-account@example.com')).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('heading', { name: '无法读取的账号记录' })).toBeVisible();
  await expect(page.getByText('damaged@example.com')).toHaveCount(0);
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: '删除损坏记录' }).click();
  await expect(page.getByRole('heading', { name: '无法读取的账号记录' })).toHaveCount(0);

  await page.getByRole('button', { name: '锁定', exact: true }).click();
  await expect(page.getByRole('heading', { name: '密码本已锁定' })).toBeVisible();
  await expect(page.getByText('work-account@example.com')).toHaveCount(0);
  await page.getByLabel('保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByRole('button', { name: '解锁密码本' }).click();
  await expect(page.getByText('work-account@example.com')).toBeVisible({ timeout: 15000 });
  await page.getByRole('button', { name: '更换密码' }).click();
  await page.getByLabel('当前保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByLabel('新保险库密码', { exact: true }).fill('更换后的保险库密码-e2e-2026');
  await page.getByLabel('确认新保险库密码').fill('更换后的保险库密码-e2e-2026');
  await page.getByRole('button', { name: '更换保险库密码' }).click();
  await page.getByRole('button', { name: '锁定', exact: true }).click();
  await page.getByLabel('保险库密码').fill('独立保险库密码-e2e-2026');
  await page.getByRole('button', { name: '解锁密码本' }).click();
  await expect(page.getByRole('alert')).toContainText('密码错误');
  await page.getByLabel('保险库密码').fill('更换后的保险库密码-e2e-2026');
  await page.getByRole('button', { name: '解锁密码本' }).click();
  await expect(page.getByText('work-account@example.com')).toBeVisible({ timeout: 15000 });
  await page.reload();
  await expect(page.getByRole('heading', { name: '密码本已锁定' })).toBeVisible();
  await page.getByRole('button', { name: '忘记密码，使用恢复密钥' }).click();
  await page.getByLabel('密码本恢复密钥', { exact: true }).fill(recoveryKey.toLowerCase());
  await page.getByLabel('新保险库密码', { exact: true }).fill('恢复后的保险库密码-e2e-2026');
  await page.getByLabel('确认新保险库密码').fill('恢复后的保险库密码-e2e-2026');
  await page.getByRole('button', { name: '恢复并设置新密码' }).click();
  await expect(page.getByText('密码本已经恢复')).toBeVisible();
  const replacedRecoveryKey = await page.getByLabel('一次性显示的密码本恢复密钥').inputValue();
  expect(replacedRecoveryKey).not.toBe(recoveryKey);
  await page.getByText('我已把恢复密钥保存在安全位置').click();
  await page.getByRole('button', { name: '我已安全保存' }).click();
  await page.getByRole('button', { name: '锁定', exact: true }).click();
  await page.getByRole('button', { name: '忘记密码，使用恢复密钥' }).click();
  await page.getByLabel('密码本恢复密钥', { exact: true }).fill(recoveryKey);
  await page.getByLabel('新保险库密码', { exact: true }).fill('旧恢复密钥不应成功的新保险库密码');
  await page.getByLabel('确认新保险库密码').fill('旧恢复密钥不应成功的新保险库密码');
  await page.getByRole('button', { name: '恢复并设置新密码' }).click();
  await expect(page.getByRole('alert')).toContainText('恢复密钥错误');
  await page.getByRole('button', { name: '取消' }).click();
  await expect(page.getByRole('heading', { name: '使用恢复密钥' })).toHaveCount(0);
  await page.getByLabel('保险库密码', { exact: true }).fill('恢复后的保险库密码-e2e-2026');
  await page.getByRole('button', { name: '解锁密码本' }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出加密备份' }).click();
  await page.getByLabel('确认保险库密码').fill('恢复后的保险库密码-e2e-2026');
  await page.getByRole('button', { name: '下载加密备份' }).click();
  await downloadPromise;
  await expect.poll(() => page.evaluate(() => globalThis.__lastDownloadedText ?? null)).not.toBeNull();
  const backup = Buffer.from(await page.evaluate(() => globalThis.__lastDownloadedText));
  expect(backup.toString('utf8')).not.toContain('企业微信');
  expect(backup.toString('utf8')).not.toContain('work-account@example.com');
  expect(backup.toString('utf8')).not.toContain('work-secret-password!');
  expect(backup.toString('utf8')).not.toContain('JBSWY3DPEHPK3PXP');

  const otherContext = await browser.newContext(), other = await otherContext.newPage();
  try {
    await other.goto(`${new URL(page.url()).origin}/vault`);
    await other.getByRole('button', { name: '从加密备份恢复' }).click();
    await other.getByLabel('选择密码本加密备份').setInputFiles({ name: 'vault-backup.json', mimeType: 'application/json', buffer: backup });
    await other.getByLabel('备份的保险库密码').fill('恢复后的保险库密码-e2e-2026');
    await other.getByRole('button', { name: '验证并导入' }).click();
    await expect(other.getByText('work-account@example.com')).toBeVisible({ timeout: 15000 });
    await other.getByRole('button', { name: '查看密码' }).click();
    await expect(other.getByText('work-secret-password!')).toBeVisible();
  } finally { await otherContext.close(); }
  expect(errors).toEqual([]);
});
